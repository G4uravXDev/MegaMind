"""API client for communicating with ZIT backend."""

from __future__ import annotations

from pathlib import Path
from typing import Any

import httpx

from zit.config import config
from zit.services.exceptions import (
    ApiAuthError,
    ApiClientError,
    ApiConnectionError,
)


class ApiClient:
    """HTTP client for ZIT AI backend services with mock support."""

    def __init__(
        self,
        base_url: str | None = None,
        token: str | None = None,
        mock: bool | None = None,
    ) -> None:
        self.base_url = (base_url or config.api_url).rstrip("/")
        self.token = token if token is not None else config.token
        self.mock = mock if mock is not None else config.mock

    def _truncate_diff(self, diff: str) -> tuple[str, bool]:
        """Truncates diff to 20,000 characters if exceeded."""
        limit = config.max_diff_chars
        if len(diff) > limit:
            truncated = (
                diff[:limit]
                + f"\n\n... [Diff truncated to {limit} characters by ZIT client] ..."
            )
            return truncated, True
        return diff, False

    def _get_headers(self) -> dict[str, str]:
        headers = {
            "Content-Type": "application/json",
            "Accept": "application/json",
        }
        if self.token:
            headers["Authorization"] = f"Token {self.token}"
        return headers

    def _post(self, endpoint: str, payload: dict[str, Any]) -> dict[str, Any]:
        """Sends POST request to backend or raises wrapped ApiClientError."""
        url = f"{self.base_url}{endpoint}"
        try:
            with httpx.Client(timeout=30.0) as client:
                response = client.post(url, json=payload, headers=self._get_headers())

            if response.status_code in (401, 403):
                raise ApiAuthError(
                    f"Authentication failed ({response.status_code}): {response.text}",
                    status_code=response.status_code,
                )

            if response.status_code >= 400:
                raise ApiClientError(
                    f"API error ({response.status_code}): {response.text}",
                    status_code=response.status_code,
                )

            return response.json()

        except httpx.ConnectError as err:
            raise ApiConnectionError(
                f"Could not connect to backend server at {self.base_url}. Is it running?"
            ) from err
        except httpx.TimeoutException as err:
            raise ApiConnectionError("Request to backend server timed out.") from err
        except httpx.HTTPError as err:
            raise ApiClientError(f"HTTP error: {err}") from err

    def commit_message(self, diff: str, recent_commits: list[str]) -> str:
        """Generates an AI commit message based on staged diff and commit history."""
        diff_text, was_truncated = self._truncate_diff(diff)

        if self.mock:
            # Canned mock response
            first_line = diff.splitlines()[0] if diff.splitlines() else "changes"
            trunc_note = " (truncated diff)" if was_truncated else ""
            return f"feat: update {first_line[:30].strip()}{trunc_note}\n\n- Generated by ZIT mock AI assistant"

        payload = {
            "diff": diff_text,
            "recent_commits": recent_commits,
            "truncated": was_truncated,
        }
        data = self._post("/api/ai/commit-message/", payload)
        message = data.get("message", "")
        if not message:
            raise ApiClientError("Backend returned an empty commit message")
        return message

    def resolve_conflict(
        self,
        file_path: str,
        ours: str,
        theirs: str,
        base: str = "",
        context_before: str = "",
        context_after: str = "",
    ) -> dict[str, str]:
        """Requests AI resolution for a merge conflict hunk."""
        if self.mock:
            return {
                "resolution": f"# Resolved by ZIT Mock\n{ours}\n{theirs}",
                "explanation": "Merged both sides (mock response).",
            }

        payload = {
            "file_path": file_path,
            "ours": ours,
            "theirs": theirs,
            "base": base,
            "context_before": context_before,
            "context_after": context_after,
        }
        data = self._post("/api/ai/resolve-conflict/", payload)
        return {
            "resolution": data.get("resolution", ""),
            "explanation": data.get("explanation", ""),
        }

    def mentor(
        self,
        question: str,
        repo_context: dict[str, Any],
        conversation_id: str | None = None,
    ) -> dict[str, Any]:
        """Asks the AI mentor a Git question with repo context."""
        if self.mock:
            return {
                "answer": (
                    f"**ZIT Mentor (Mock Mode)**\n\n"
                    f"You asked: *{question}*\n\n"
                    f"On branch `{repo_context.get('branch', 'unknown')}`: "
                    "Make sure your working directory is clean before branching or pulling."
                ),
                "conversation_id": conversation_id or "mock-conv-123",
            }

        payload = {
            "question": question,
            "repo_context": repo_context,
            "conversation_id": conversation_id,
        }
        data = self._post("/api/ai/mentor/", payload)
        return {
            "answer": data.get("answer", ""),
            "conversation_id": data.get("conversation_id", conversation_id),
        }

    def coverage(self, file_path: str, source: str) -> str:
        """Requests generated test coverage for a file source."""
        if self.mock:
            return (
                f"# Generated test suite for {file_path} (Mock)\n\n"
                f"import pytest\n\n"
                f"def test_{Path(file_path).stem}_basic():\n"
                f"    assert True\n"
            )

        payload = {
            "file_path": file_path,
            "source": source,
        }
        data = self._post("/api/ai/coverage/", payload)
        return data.get("tests", "")
